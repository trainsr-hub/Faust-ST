export function buildCanonicalLinkageDatabase(): Record<string, LinkageNodeData> {
  const db: Record<string, LinkageNodeData> = {};

  // 1. Register Concept Hub Roots (Top-level Structural Ancestors)
  CANONICAL_CONCEPT_HUBS.forEach((hub) => {
    db[hub.id] = {
      id: hub.id,
      tag: hub.customLabel,
      customLabel: hub.customLabel,
      isTagless: true,
      category: hub.category,
      subcategory: hub.subcategory,
      description: `Danbooru Structural Concept: ${hub.customLabel}`,
      wikiUrl: 'https://danbooru.donmai.us/wiki_pages/tag_group:hair_styles',
      isDiscarded: false,
      links_to: {},
    };
  });

  // 2. Register Danbooru Traits
  DANBOORU_HAIR_ITEMS.forEach((it: any) => {
    const slug = it.slug || it.id || it.tag.replace(/ /g, '_');
    db[slug] = {
      id: slug,
      tag: it.tag,
      image: it.imageUrl,
      category: it.category || 'General',
      subcategory: it.subcategory || it.category || 'General',
      description: it.description,
      wikiUrl: it.wikiUrl || `https://danbooru.donmai.us/wiki_pages/${slug}`,
      isDiscarded: false,
      links_to: {},
    };
  });

  // 3. Connect Canonical Linkages (A => B: B depends on A)
  CANONICAL_HAIR_LINKS.forEach(([src, tgt]) => {
    if (db[src] && db[tgt] && src !== tgt) {
      db[src].links_to = db[src].links_to || {};
      db[src].links_to[tgt] = true;
    }
  });

  return db;
}
